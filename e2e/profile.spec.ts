import { expect, test } from '@playwright/test';
import type { Locator } from '@playwright/test';
import { SAVE_KEY } from '../src/persistence/profile-store';

// Only backups/storage are fixtures here; combat state is never injected.
test('save mixed builds, research, reload, export/import, and play an earned larger build', async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.clock.install();
  await page.clock.pauseAt(new Date());
  await page.goto('/');
  const activate = async (node: Locator) => testInfo.project.use.hasTouch ? node.tap() : node.click();
  const editor = page.getByRole('dialog', { name: 'Classless talents' });
  await activate(page.locator('#edit-talents'));
  await activate(editor.getByRole('button', { name: /Inspect Iron Reprisal/ }));
  await activate(editor.locator('#allocate-talent'));
  await activate(editor.getByRole('tab', { name: /Mage/ }));
  await activate(editor.getByRole('button', { name: /Inspect Arcane Echo/ }));
  await activate(editor.locator('#allocate-talent'));
  await activate(editor.locator('#profile-panel > summary'));
  await editor.locator('#build-name').fill('Ember and Steel');
  await activate(editor.locator('#save-build'));
  await expect(editor.locator('#profile-message')).toHaveText('Build saved in this slot.');
  await activate(editor.getByRole('tab', { name: /Warrior/ }));
  await activate(editor.getByRole('button', { name: /Inspect Last Stand/ }));
  await expect(editor.locator('#allocate-talent')).toBeDisabled();
  await activate(editor.locator('#research-talent'));
  await expect(editor.locator('#profile-summary')).toContainText('1 insight');
  await expect(editor.locator('#research-talent')).toBeHidden();
  await activate(editor.locator('#close-talents'));
  await page.reload();
  await expect(page.locator('#edit-talents')).toHaveText('Talents (2/8)');
  await activate(page.locator('#edit-talents'));
  await activate(editor.locator('#profile-panel > summary'));
  await expect(editor.locator('#build-slot option').first()).toContainText('Ember and Steel');
  await activate(editor.locator('#respec-talents'));
  await expect(editor.locator('#talent-points')).toContainText('0 / 8');
  await activate(editor.locator('#load-build'));
  await expect(editor.locator('#talent-points')).toContainText('2 / 8');
  await activate(editor.getByRole('button', { name: /Inspect Last Stand/ }));
  await expect(editor.locator('#research-talent')).toBeHidden();
  await activate(editor.locator('#profile-panel details > summary'));
  const download = page.waitForEvent('download');
  await activate(editor.locator('#export-backup'));
  expect((await download).suggestedFilename()).toBe('classless-survivors-backup.json');
  const backup = await editor.locator('#backup-text').inputValue();
  expect(JSON.parse(backup).draft).toEqual(['reprisal', 'arcane-echo']);
  await editor.locator('#backup-text').fill('{broken');
  await activate(editor.locator('#review-backup'));
  await expect(editor.locator('#profile-message')).toContainText('not valid JSON');
  await expect(editor.locator('#confirm-import')).toBeHidden();
  await expect(editor.locator('#talent-points')).toContainText('2 / 8');
  await activate(editor.locator('#respec-talents'));
  await editor.locator('#backup-file').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(backup) });
  await expect(editor.locator('#backup-text')).toHaveValue(backup);
  await activate(editor.locator('#review-backup'));
  await expect(editor.locator('#import-preview')).toContainText('Replace this device');
  await activate(editor.locator('#confirm-import'));
  await expect(editor.locator('#talent-points')).toContainText('2 / 8');
  // Early-format backups migrate through the same reviewed import path.
  await editor.locator('#backup-text').fill(JSON.stringify({ version: 1, build: ['reprisal', 'arcane-echo'], completedRuns: 2 }));
  await activate(editor.locator('#review-backup')); await activate(editor.locator('#confirm-import'));
  await expect(editor.locator('#talent-points')).toContainText('2 / 9');
  // Import a valid progressed backup through the user-facing restore path.
  const earned = { ...JSON.parse(backup), completedRuns: 5, nextRunId: 6 };
  await editor.locator('#backup-text').fill(JSON.stringify(earned));
  await activate(editor.locator('#review-backup')); await activate(editor.locator('#confirm-import'));
  await expect(editor.locator('#profile-summary')).toContainText('10 talent points');
  await expect(editor.locator('#talent-points')).toContainText('2 / 10');
  await activate(editor.locator('#profile-panel > summary'));
  for (const talent of ['Sweeping Blade', 'Spellsteel', 'Frostbreak', 'Iron Ward', 'Last Stand']) {
    await activate(editor.getByRole('button', { name: new RegExp(`Inspect ${talent}`) }));
    await activate(editor.locator('#allocate-talent'));
  }
  await activate(editor.getByRole('tab', { name: /Mage/ }));
  await activate(editor.getByRole('button', { name: /Inspect Rime Sigil/ })); await activate(editor.locator('#allocate-talent'));
  await activate(editor.getByRole('tab', { name: /Rogue/ }));
  await activate(editor.getByRole('button', { name: /Inspect Expose Weakness/ })); await activate(editor.locator('#allocate-talent'));
  await expect(editor.locator('#talent-points')).toContainText('9 / 10');
  expect(await editor.evaluate((node) => node.scrollWidth <= node.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('saved-progression.png'), fullPage: true });
  await activate(editor.locator('#close-talents'));
  await activate(page.locator('#start-run'));
  await page.clock.runFor(64);
  await page.locator('#run-build summary').click();
  await expect(page.locator('#active-talents li')).toHaveCount(9);
  expect(errors).toEqual([]);
});

test('recover corrupted saves, preserve newer formats, and allow play/export without storage', async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  await page.addInitScript(() => {
    if (sessionStorage.getItem('deny-save')) Object.defineProperty(window, 'localStorage', { get() { throw new DOMException('Storage disabled', 'SecurityError'); } });
  });
  await page.goto('/');
  const activate = async (node: Locator) => testInfo.project.use.hasTouch ? node.tap() : node.click();
  const editor = page.getByRole('dialog', { name: 'Classless talents' });
  await activate(page.locator('#edit-talents'));
  await activate(editor.getByRole('button', { name: /Inspect Iron Reprisal/ })); await activate(editor.locator('#allocate-talent'));
  await activate(editor.getByRole('tab', { name: /Mage/ }));
  await activate(editor.getByRole('button', { name: /Inspect Arcane Echo/ })); await activate(editor.locator('#allocate-talent'));
  await page.evaluate((key) => localStorage.setItem(key, '{damaged'), SAVE_KEY);
  await page.reload();
  await expect(page.locator('#edit-talents')).toHaveText('Talents (1/8)');
  await activate(page.locator('#edit-talents'));
  await expect(editor.locator('#save-status')).toContainText('Recovered the previous');
  await page.evaluate((key) => localStorage.setItem(key, JSON.stringify({ version: 99, future: 'preserve' })), SAVE_KEY);
  await page.reload(); await activate(page.locator('#edit-talents'));
  await expect(editor.locator('#save-status')).toContainText('newer game version');
  await activate(editor.getByRole('button', { name: /Inspect Iron Reprisal/ })); await activate(editor.locator('#allocate-talent'));
  expect(await page.evaluate((key) => JSON.parse(localStorage.getItem(key)!).future, SAVE_KEY)).toBe('preserve');
  await page.evaluate(() => sessionStorage.setItem('deny-save', 'true'));
  await page.reload(); await activate(page.locator('#edit-talents'));
  await expect(editor.locator('#save-status')).toContainText('Local saving is unavailable');
  await activate(editor.getByRole('button', { name: /Inspect Iron Reprisal/ })); await activate(editor.locator('#allocate-talent'));
  await expect(editor.locator('#talent-points')).toContainText('1 / 8');
  await activate(editor.locator('#profile-panel > summary')); await activate(editor.locator('#profile-panel details > summary'));
  const download = page.waitForEvent('download'); await activate(editor.locator('#export-backup')); await download;
  expect(JSON.parse(await editor.locator('#backup-text').inputValue()).draft).toEqual(['reprisal']);
  await activate(editor.locator('#close-talents')); await activate(page.locator('#start-run'));
  await expect(page.locator('#pause-run')).toBeVisible();
});
